#!/usr/bin/env python3
"""muse_art.py: the Table for Two design pipeline on Muse Image (SPEC section 7).

Every image is generated by `muse-image-1.0` through the Meta Model API
(`POST https://api.meta.ai/v1/images/generations`, OpenAI images shape, WebP in
`data[0].b64_json`) with the house style suffix from design/muse-explorations/PROMPTS.md
appended verbatim, so the icon set, hero art and venue plates read as one print run.

  python scripts/muse_art.py icons                      # app-icon directions -> design/candidates/icons/
  python scripts/muse_art.py hero                       # Get-me-in panel hero -> design/candidates/hero/
  python scripts/muse_art.py venues --city nyc --ids carbone,marea   # art/<city>/<id>.webp
  python scripts/muse_art.py prompt "subject" --out design/candidates/x.webp --size 1024x1024
  python scripts/muse_art.py build-icons design/candidates/icons/chairs-1.webp   # -> icons/*.png
  python scripts/muse_art.py gallery                    # design/candidates/index.html

Results are cached by prompt+size hash in design/.cache/ so re-running a command never
re-bills an unchanged prompt. The key is resolved like the agent's (agent.config.api_key).
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
import time
from io import BytesIO
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from agent import config  # noqa: E402  (key lookup + base URL)

DESIGN = ROOT / "design"
CANDIDATES = DESIGN / "candidates"
CACHE = DESIGN / ".cache"
ART = ROOT / "art"
ICONS = ROOT / "icons"
MODEL = "muse-image-1.0"
URL = f"{config.META_BASE_URL}/v1/images/generations"

STYLE = (
    "Original editorial halftone dot-screen illustration, coarse printed grain, two-colour "
    "risograph feel in deep ink black and warm cream with one bone-white highlight, no text, "
    "no letters, no emoji, no gradients, flat graphic shapes, high contrast, luxury-minimal "
    "restaurant brand."
)

# App-icon directions. Each is a (slug, subject) pair; the style suffix is appended.
ICON_DIRECTIONS = [
    ("chairs", "App icon mark: two empty chairs facing each other across a small round table, "
               "seen straight from above, the whole mark built from halftone dots, centred on a "
               "solid cream square with a generous margin, nothing else in frame."),
    ("bell", "App icon mark: a single ringing bell above a dinner plate, the alert for an "
             "impossible restaurant table, halftone dot-screen graphic on a solid ink-black "
             "square, centred, generous margin, nothing else in frame."),
    ("candle", "App icon mark: one lit candle on a small round table with two empty chairs, "
               "seen from the side as a tight symmetric silhouette, halftone dots, solid "
               "ink-black square, warm cream light, centred, generous margin."),
    ("plate-clock", "App icon mark: a dinner plate whose rim is a clock face with the hands at "
                    "one minute to ten, fork and knife as the hands, halftone dot-screen, solid "
                    "cream square, centred, generous margin, nothing else in frame."),
]

HERO_DIRECTIONS = [
    ("doorway", "Wide hero illustration: a maître d' stand and an open doorway into a glowing "
                "dining room seen from the dark street, one empty table for two visible inside "
                "under a single lamp, coarse halftone dot screen, cinematic, dark ink background "
                "with warm cream light, no people."),
    ("ten-oclock", "Wide hero illustration: the second before reservations drop, a wall clock at "
                   "9:59, a phone glowing on an empty candlelit table for two, coarse halftone "
                   "dot screen, cinematic composition, dark ink background with warm cream light."),
    ("city-table", "Wide hero illustration: a single set table for two floating above a dense "
                   "city skyline at night, candle lit, rooftops and water towers below, coarse "
                   "halftone dot screen, dark ink sky with warm cream highlights, poster-like."),
]


def _key(prompt: str, size: str) -> str:
    return hashlib.sha1(f"{MODEL}|{size}|{prompt}".encode("utf-8")).hexdigest()[:16]


def generate(subject: str, size: str = "1024x1024", style: bool = True, n: int = 1) -> list[bytes]:
    """WebP bytes for a subject prompt (+ house style). Cached per prompt and size."""
    prompt = f"{subject.strip()} {STYLE}" if style else subject.strip()
    CACHE.mkdir(parents=True, exist_ok=True)
    out: list[bytes] = []
    for i in range(n):
        cached = CACHE / f"{_key(prompt, size)}-{i}.webp"
        if cached.exists():
            out.append(cached.read_bytes())
            continue
        t0 = time.time()
        for attempt in range(3):   # the image endpoint drops connections now and then
            try:
                r = requests.post(URL, headers={"Authorization": f"Bearer {config.api_key()}"},
                                  json={"model": MODEL, "prompt": prompt, "n": 1, "size": size}, timeout=180)
                break
            except requests.ConnectionError as e:
                if attempt == 2:
                    raise SystemExit(f"Muse Image unreachable after 3 tries: {e}")
                time.sleep(3 * (attempt + 1))
        if r.status_code != 200:
            raise SystemExit(f"Muse Image answered {r.status_code}: {r.text[:300]}")
        data = r.json()["data"][0]
        img = base64.b64decode(data["b64_json"])
        cached.write_bytes(img)
        print(f"  generated {size} in {time.time() - t0:.1f}s ({len(img) // 1024} KB)")
        out.append(img)
    return out


def save(img: bytes, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(img)
    return path


def _manifest_add(folder: Path, row: dict) -> None:
    mf = folder / "manifest.json"
    rows = json.loads(mf.read_text(encoding="utf-8")) if mf.exists() else []
    rows = [r for r in rows if r.get("file") != row["file"]] + [row]
    mf.write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf-8")


# ---- commands --------------------------------------------------------------------

def cmd_icons(a: argparse.Namespace) -> None:
    folder = CANDIDATES / "icons"
    for slug, subject in ICON_DIRECTIONS:
        if a.only and slug not in a.only:
            continue
        print(f"icon direction: {slug}")
        for i, img in enumerate(generate(subject, "1024x1024", n=a.n), 1):
            p = save(img, folder / f"{slug}-{i}.webp")
            _manifest_add(folder, {"file": p.name, "direction": slug, "subject": subject, "size": "1024x1024"})
            print(f"  -> {p.relative_to(ROOT)}")


def cmd_hero(a: argparse.Namespace) -> None:
    folder = CANDIDATES / "hero"
    for slug, subject in HERO_DIRECTIONS:
        if a.only and slug not in a.only:
            continue
        print(f"hero direction: {slug}")
        for i, img in enumerate(generate(subject, "1536x1024", n=a.n), 1):
            p = save(img, folder / f"{slug}-{i}.webp")
            _manifest_add(folder, {"file": p.name, "direction": slug, "subject": subject, "size": "1536x1024"})
            print(f"  -> {p.relative_to(ROOT)}")


def venue_subject(spot: dict) -> str:
    dish = spot.get("signatureDish") or f"the signature dish of a {spot.get('cuisine', '')} restaurant"
    vibe = ", ".join(spot.get("vibe") or [])
    return (f"Square venue-card art: overhead view of {dish} plated on dark linen with one glass, "
            f"{spot.get('cuisine', '')} cooking, mood {vibe or 'intimate'}, abstracted into a bold "
            f"halftone dot-screen print, chiaroscuro lighting, poster-like, no people, no text.")


def cmd_venues(a: argparse.Namespace) -> None:
    city = a.city
    data = json.loads((ROOT / "cities" / f"{city}.json").read_text(encoding="utf-8"))
    spots = data["spots"] if isinstance(data, dict) else data
    want = {s.strip() for s in (a.ids or "").split(",") if s.strip()}
    folder = ART / city
    for s in spots:
        if want and s["id"] not in want:
            continue
        if not want and len(list(folder.glob("*.webp"))) >= a.limit:
            break
        print(f"venue: {s['name']} ({s.get('signatureDish')})")
        img = generate(venue_subject(s), "1024x1024")[0]
        p = save(img, folder / f"{s['id']}.webp")
        _manifest_add(folder, {"file": p.name, "id": s["id"], "name": s["name"], "dish": s.get("signatureDish"),
                               "model": MODEL, "generated": time.strftime("%Y-%m-%d")})
        print(f"  -> {p.relative_to(ROOT)}")


def cmd_prompt(a: argparse.Namespace) -> None:
    img = generate(a.subject, a.size, style=not a.raw)[0]
    p = save(img, Path(a.out))
    print(f"-> {p}")


def cmd_build_icons(a: argparse.Namespace) -> None:
    """Cut the PWA/app icon set (PNG) from one 1024x1024 candidate WebP."""
    from PIL import Image
    src = Image.open(a.source).convert("RGBA")
    w, h = src.size
    side = min(w, h)
    sq = src.crop(((w - side) // 2, (h - side) // 2, (w - side) // 2 + side, (h - side) // 2 + side))
    if a.crop:   # trim a fraction off every edge so a framed candidate fills the tile
        c = int(side * a.crop)
        sq = sq.crop((c, c, side - c, side - c))
        side = sq.size[0]
    # Maskable icons need the mark inside the central 80%: pad with the corner colour.
    bg = sq.getpixel((4, 4))
    pad = int(side * a.pad)
    canvas = Image.new("RGBA", (side + 2 * pad, side + 2 * pad), bg)
    canvas.paste(sq, (pad, pad))
    out = {
        "icon-512.png": 512, "icon-192.png": 192, "apple-touch-icon.png": 180,
        "favicon.png": 64, "mark.png": 256,
    }
    ICONS.mkdir(exist_ok=True)
    for name, px in out.items():
        im = canvas if name != "mark.png" else sq
        im.resize((px, px), Image.LANCZOS).save(ICONS / name, "PNG", optimize=True)
        print(f"  -> icons/{name} ({px}px)")
    # Keep the source next to the icons so the choice is traceable.
    (ICONS / "source.txt").write_text(f"{Path(a.source).as_posix()} via Muse Image ({MODEL})\n", encoding="utf-8")


def cmd_gallery(a: argparse.Namespace) -> None:
    """A single HTML page of every candidate (inline WebP) for choosing between them."""
    from PIL import Image

    def thumb(f: Path, px: int = 720) -> str:
        im = Image.open(f).convert("RGB")
        im.thumbnail((px, px), Image.LANCZOS)
        buf = BytesIO()
        im.save(buf, "WEBP", quality=78)
        return base64.b64encode(buf.getvalue()).decode()

    rows = []
    for folder in sorted(p for p in CANDIDATES.iterdir() if p.is_dir()):
        for f in sorted(folder.glob("*.webp")):
            rows.append((folder.name, f.name, thumb(f)))
    for city in sorted(p for p in ART.iterdir() if p.is_dir()) if ART.exists() else []:
        for f in sorted(city.glob("*.webp")):
            rows.append((f"art/{city.name}", f.name, thumb(f)))
    cards = "\n".join(
        f'<figure><img src="data:image/webp;base64,{b64}" loading="lazy" alt="{group}/{name}">'
        f'<figcaption><b>{group}</b> {name}</figcaption></figure>' for group, name, b64 in rows)
    html = f"""<!doctype html><meta charset="utf-8"><title>Muse Image candidates</title>
<style>body{{margin:0;background:#0a0a0b;color:#f4f3f1;font:14px/1.5 Inter,system-ui,sans-serif;padding:24px}}
h1{{font-weight:500;letter-spacing:3px;text-transform:uppercase;font-size:14px;color:#c9a86a}}
.g{{display:grid;grid-template-columns:repeat(auto-fill,minmax(280px,1fr));gap:18px}}
figure{{margin:0;background:#101011;border:1px solid #212124;border-radius:14px;padding:10px}}
img{{width:100%;height:auto;border-radius:9px;display:block}}figcaption{{margin-top:8px;color:#8a8a90;font-size:12px}}b{{color:#dcc28c}}</style>
<h1>Muse Image candidates ({len(rows)})</h1><div class="g">{cards}</div>"""
    out = CANDIDATES / "index.html"
    out.write_text(html, encoding="utf-8")
    print(f"-> {out.relative_to(ROOT)} ({len(rows)} images)")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("icons"); s.add_argument("--only", nargs="*"); s.add_argument("--n", type=int, default=1)
    s = sub.add_parser("hero"); s.add_argument("--only", nargs="*"); s.add_argument("--n", type=int, default=1)
    s = sub.add_parser("venues"); s.add_argument("--city", default="nyc"); s.add_argument("--ids"); s.add_argument("--limit", type=int, default=6)
    s = sub.add_parser("prompt"); s.add_argument("subject"); s.add_argument("--out", required=True)
    s.add_argument("--size", default="1024x1024"); s.add_argument("--raw", action="store_true", help="no style suffix")
    s = sub.add_parser("build-icons"); s.add_argument("source"); s.add_argument("--pad", type=float, default=0.0)
    s.add_argument("--crop", type=float, default=0.0, help="fraction trimmed off each edge before resizing")
    sub.add_parser("gallery")
    a = ap.parse_args(argv)
    {"icons": cmd_icons, "hero": cmd_hero, "venues": cmd_venues, "prompt": cmd_prompt,
     "build-icons": cmd_build_icons, "gallery": cmd_gallery}[a.cmd](a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
